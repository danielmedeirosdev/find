import { test, expect } from '@playwright/test'
import fs from 'node:fs'
import { data } from './api'
const account=JSON.parse(fs.readFileSync(process.env.ONEFIND_QA_ACCOUNT||'/tmp/onefind-qa-account.json','utf8'))
const fixture=JSON.parse(fs.readFileSync('/tmp/onefind-qa-fixture.json','utf8'))
test('phone locates the profile while the customer name and pet stay linked', async({page})=>{
 await page.setViewportSize({width:375,height:812})
 await page.goto('/painel')
 await page.getByPlaceholder('Ex: contato@negocio.com').fill(account.email)
 await page.getByPlaceholder('Sua senha').fill(account.password)
 await page.getByRole('button',{name:'Entrar',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Seu dia no onefind'})).toBeVisible({timeout:30000})
 const phone='199'+String(Date.now()).slice(-8)
 const lookup=async()=>{
  await page.getByRole('button',{name:'+ Buscar ou cadastrar por WhatsApp',exact:true}).click()
  await page.getByLabel('WhatsApp do cliente',{exact:true}).fill(phone)
  await page.getByRole('button',{name:'Usar este WhatsApp',exact:true}).click()
  await expect(page.getByTestId('customer-contact')).toContainText('WhatsApp do cadastro')
 }
 await page.goto('/painel/dashboard?aba=agenda')
 await page.getByRole('button',{name:'+ Novo agendamento',exact:true}).click()
 await lookup()
 const contact=(await data(page,`shop_customers?shop_id=eq.${fixture.shopId}&phone=eq.${phone}`))[0]
 const client=page.getByRole('combobox',{name:'Cliente',exact:true})
 await expect(client.locator('option:checked')).toHaveText('Nome não informado')
 await page.getByRole('button',{name:'+ Cadastrar pet aqui',exact:true}).click()
 await page.getByLabel('Nome do pet',{exact:true}).fill('Laura QA')
 await page.getByRole('button',{name:'Salvar pet e selecionar',exact:true}).click()
 await expect(client.locator('option:checked')).toHaveText('Responsável por Laura QA')
 await page.getByLabel('Nome do cliente (opcional)',{exact:true}).fill('Mariana QA')
 await page.getByRole('button',{name:'Salvar nome do cliente',exact:true}).click()
 await expect(client.locator('option:checked')).toHaveText('Mariana QA')
 await expect(client).toHaveValue(contact.id)
 const pets=await data(page,`pets?customer_id=eq.${contact.id}`)
 await expect(page.getByRole('combobox',{name:'Pet',exact:true})).toHaveValue(pets[0].id)
 await lookup()
 await expect(client.locator('option:checked')).toHaveText('Mariana QA')
 expect(await data(page,`shop_customers?shop_id=eq.${fixture.shopId}&phone=eq.${phone}`)).toHaveLength(1)
 expect((await data(page,`shop_customers?id=eq.${contact.id}`))[0].name).toBe('Mariana QA')
 await expect(page.getByRole('combobox',{name:'Pet',exact:true}).locator(`option[value="${pets[0].id}"]`)).toHaveText('Laura QA')
 for(const width of [320,375,390,430]){await page.setViewportSize({width,height:812});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)}
 await page.screenshot({path:'/tmp/onefind-client-name-separated.png',fullPage:true})
})
test('confirmation reminders persist and the real cron alerts the establishment with a prepared WhatsApp message', async({page})=>{
 test.setTimeout(240000)
 await page.setViewportSize({width:390,height:844})
 await page.goto('/painel')
 await page.getByPlaceholder('Ex: contato@negocio.com').fill(account.email)
 await page.getByPlaceholder('Sua senha').fill(account.password)
 await page.getByRole('button',{name:'Entrar',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Seu dia no onefind'})).toBeVisible({timeout:30000})
 const previous=await data(page,`bookings?shop_id=eq.${fixture.shopId}&status=eq.scheduled&confirmation_reminder_minutes=not.is.null&select=id`)
 for(const old of previous)await data(page,'rpc/set_booking_confirmation_reminder','POST',{p_booking_id:old.id,p_minutes:null})
 const staff=(await data(page,'barbers','POST',{shop_id:fixture.shopId,name:'QA Lembrete '+Date.now()}))[0]
 const service=(await data(page,'services','POST',{shop_id:fixture.shopId,name:'QA Banho Lembrete '+Date.now(),price:50,duration_minutes:15}))[0]
 await data(page,'barber_schedule','POST',Array.from({length:7},(_,day)=>({barber_id:staff.id,day_of_week:day,is_active:true,start_time:'00:00',end_time:'23:59'})))
 const serverTime=await data(page,'rpc/current_booking_time','POST',{})
 const target=new Date(Math.ceil((Date.parse(serverTime)+2*3600000)/3600000)*3600000)
 const parts=new Intl.DateTimeFormat('en-CA',{timeZone:'America/Sao_Paulo',year:'numeric',month:'2-digit',day:'2-digit',hour:'2-digit',minute:'2-digit',hourCycle:'h23'}).formatToParts(target)
 const part=(name:string)=>parts.find(item=>item.type===name)!.value
 const date=`${part('year')}-${part('month')}-${part('day')}`,time=`${part('hour')}:${part('minute')}`
 const id=await data(page,'rpc/create_operational_booking','POST',{p_shop_id:fixture.shopId,p_barber_id:staff.id,p_customer_id:fixture.customerId,p_pet_id:fixture.petId,p_date:date,p_time:time,p_service_ids:[service.id]})
 await page.goto('/painel/dashboard?aba=agenda')
 await page.getByRole('button',{name:'Próximos',exact:true}).click()
 const card=page.getByTestId(`booking-${id}`)
 const message=new URL((await card.getByRole('link',{name:'Confirmar pelo WhatsApp',exact:true}).getAttribute('href'))!).searchParams.get('text')!
 expect(message).toContain(service.name);expect(message).toContain(time);expect(message).not.toContain(':00:00')
 await card.getByRole('combobox',{name:'Lembrar de confirmar',exact:true}).selectOption('120')
 await expect.poll(async()=>(await data(page,`bookings?id=eq.${id}`))[0].confirmation_reminder_minutes).toBe(120)
 await card.getByRole('combobox',{name:'Lembrar de confirmar',exact:true}).selectOption('1440')
 await expect(card.getByText('Lembrete programado.',{exact:true})).toBeVisible()
 for(const width of [320,375,390,430]){await page.setViewportSize({width,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)}
 // Wait for the actual existing minute cron, without invoking a global worker.
 await expect.poll(async()=>(await data(page,`bookings?id=eq.${id}`))[0].confirmation_reminder_sent_at,{timeout:90000,intervals:[3000,5000]}).toBeTruthy()
 expect(await data(page,`notifications?booking_id=eq.${id}&kind=eq.booking_confirmation_reminder`)).toHaveLength(1)
 await page.goto('/painel/dashboard?aba=overview')
 const alert=page.getByRole('complementary',{name:'Lembretes de confirmação',exact:true})
 await expect(alert).toBeVisible({timeout:20000})
 await alert.getByRole('button',{name:'Ver na agenda',exact:true}).first().click()
 await expect(page.getByRole('heading',{name:'Agenda',exact:true})).toBeVisible()
 await expect(page.getByTestId(`booking-${id}`)).toBeVisible()
 await page.goto('/painel/dashboard?aba=notifications')
 await expect(page.getByRole('heading',{name:'Notificações',exact:true})).toBeVisible()
 await expect(page.getByRole('link',{name:'Ver na agenda',exact:true}).first()).toBeVisible()
 await page.goto(`/painel/dashboard?aba=agenda&atendimento=${id}`)
 await expect(card.getByRole('combobox',{name:'Lembrar de confirmar',exact:true})).toHaveValue('1440')
 await card.getByRole('combobox',{name:'Lembrar de confirmar',exact:true}).selectOption('')
 await expect.poll(async()=>(await data(page,`bookings?id=eq.${id}`))[0].confirmation_reminder_minutes).toBeNull()
 await expect(page.getByRole('complementary',{name:'Lembretes de confirmação',exact:true})).toHaveCount(0)
})
