import {test,expect} from '@playwright/test'
import crypto from 'node:crypto'
import {data} from './api'
test('new pet shop signup, settings, customer, pet, catalogue, booking and package',async({page})=>{
 test.setTimeout(240000)
 const email=`qa.onefind.full.${Date.now()}@example.com`, password='A1!'+crypto.randomBytes(20).toString('base64url')
 await page.setViewportSize({width:390,height:844})
 console.log('Stage: /painel?modo=cadastro')
 await page.goto('/painel?modo=cadastro')
 await expect(page.getByRole('heading',{name:'Cadastrar negócio'})).toBeVisible()
 await page.locator('input[type=text]').fill('QA Pet Shop completo')
 await page.getByLabel('E-mail',{exact:true}).fill(email)
 await page.getByLabel('Senha',{exact:true}).fill(password)
 await page.getByRole('button',{name:'Criar conta',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Seu dia no onefind'})).toBeVisible({timeout:30000})
 const shop=(await data(page,'shops?select=*'))[0]
 console.log('Stage: /painel/dashboard?aba=info')
 await page.goto('/painel/dashboard?aba=info')
 await page.getByPlaceholder('Ex: Banho & Tosa da Maria').fill('QA Pet Shop configurado')
 await page.getByPlaceholder('Ex: Rua das Palmeiras, 482 - Centro').fill('Rua Fictícia, 123')
 await page.getByPlaceholder('Ex: (11) 99999-9999').fill('19999990000')
 await page.getByRole('button',{name:'Salvar',exact:true}).click()
 await expect.poll(async()=>(await data(page,`shops?id=eq.${shop.id}`))[0].name).toBe('QA Pet Shop configurado')
 console.log('Stage: /painel/dashboard?aba=customers')
 await page.goto('/painel/dashboard?aba=customers')
 await page.getByText('Cadastrar cliente',{exact:true}).click()
 await page.getByPlaceholder('Ex: Maria Silva').fill('Tutor do teste completo')
 await page.getByPlaceholder('Ex: (11) 99999-9999').fill('19999991111')
 await page.getByRole('button',{name:'Adicionar',exact:true}).click()
 await expect.poll(async()=>(await data(page,`shop_customers?shop_id=eq.${shop.id}`)).length).toBe(1)
 const customer=(await data(page,`shop_customers?shop_id=eq.${shop.id}`))[0]
 console.log('Stage: /painel/dashboard?aba=pets')
 await page.goto('/painel/dashboard?aba=pets')
 await page.getByRole('button',{name:'+ Novo pet',exact:true}).click()
 await page.getByPlaceholder('Ex: Thor').fill('Luna do teste completo')
 await page.locator('select').filter({has:page.locator(`option[value="${customer.id}"]`)}).selectOption(customer.id)
 await page.getByRole('button',{name:'Salvar pet',exact:true}).click()
 await expect.poll(async()=>(await data(page,`pets?shop_id=eq.${shop.id}`)).length).toBe(1)
 const pet=(await data(page,`pets?shop_id=eq.${shop.id}`))[0]
 console.log('Stage: /painel/dashboard?aba=services')
 await page.goto('/painel/dashboard?aba=services')
 for(const [name,price,minutes] of [['QA Banho','50','30'],['QA Hidratação','20','15'],['QA Unhas','10','15']]){
  await page.getByPlaceholder('Ex: Banho + Tosa').fill(name)
  await page.getByPlaceholder('Ex: 80,00').fill(price)
  await page.getByLabel('Minutos para qualquer porte').fill(minutes)
  await page.getByRole('button',{name:'Adicionar',exact:true}).click()
  await expect(page.getByPlaceholder('Ex: Banho + Tosa')).toHaveValue('')
 }
 const services=await data(page,`services?shop_id=eq.${shop.id}&name=like.QA*&order=name`)
 expect(services).toHaveLength(3)
 console.log('Stage: /painel/dashboard?aba=team')
 await page.goto('/painel/dashboard?aba=team')
 await page.getByPlaceholder('Ex: Maria Tosadora').fill('QA Profissional completo')
 await page.getByRole('button',{name:'Adicionar',exact:true}).click()
 await expect(page.getByRole('heading',{name:'QA Profissional completo'})).toBeVisible()
 const professional=(await data(page,`barbers?shop_id=eq.${shop.id}&name=eq.QA%20Profissional%20completo`))[0]
 console.log('Stage: /painel/dashboard?aba=packages')
 await page.goto('/painel/dashboard?aba=packages')
 const model=page.getByRole('heading',{name:'Novo modelo',exact:true}).locator('..')
 for(const [i,value] of ['QA Pacote','4','200','90'].entries())await model.locator('input').nth(i).fill(value)
 await model.getByRole('button',{name:'Criar modelo'}).click()
 const template=(await data(page,`service_packages?shop_id=eq.${shop.id}&name=eq.QA%20Pacote`))[0]
 const assignment=page.getByRole('heading',{name:'Associar a cliente / pet'}).locator('..')
 await assignment.locator('select').nth(0).selectOption(template.id)
 await assignment.locator('select').nth(1).selectOption(customer.id)
 await assignment.locator('select').nth(2).selectOption(pet.id)
 await assignment.getByRole('checkbox').check()
 await assignment.getByRole('button',{name:'Associar pacote',exact:true}).click()
 await expect.poll(async()=>(await data(page,`customer_packages?shop_id=eq.${shop.id}`)).length).toBe(1)
 const pkg=(await data(page,`customer_packages?shop_id=eq.${shop.id}`))[0]
 console.log('Stage: /painel/dashboard?aba=agenda')
 await page.goto('/painel/dashboard?aba=agenda')
 await page.getByRole('button',{name:'+ Novo agendamento',exact:true}).click()
 await page.getByLabel('Cliente',{exact:true}).selectOption(customer.id)
 await page.getByLabel('Pet',{exact:true}).selectOption(pet.id)
 await page.getByRole('button',{name:'Continuar',exact:true}).click()
 await page.getByRole('checkbox',{name:/QA Banho/}).check()
 await page.getByRole('checkbox',{name:/QA Hidratação/}).check()
 await page.getByLabel('Profissional',{exact:true}).selectOption(professional.id)
 await page.getByRole('button',{name:'Continuar',exact:true}).click()
 await page.getByLabel('Horário',{exact:true}).fill('13:00')
 await page.getByRole('button',{name:'Confirmar agendamento',exact:true}).click()
 await expect(page.getByRole('button',{name:'Concluir',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Concluir',exact:true}).click()
 const b=(await data(page,`bookings?shop_id=eq.${shop.id}`))[0]
 const card=page.getByTestId(`booking-${b.id}`)
 await card.getByRole('button',{name:'Confirmar',exact:true}).click()
 await expect(card.getByRole('button',{name:'Iniciar',exact:true})).toBeVisible()
 await card.getByRole('button',{name:'Iniciar',exact:true}).click()
 await card.getByRole('button',{name:'Finalizar atendimento',exact:true}).click()
 const checkout=page.getByRole('dialog',{name:'Finalizar atendimento'})
 await checkout.locator('select').selectOption(pkg.id)
 await expect(checkout.getByText('R$ 0,00',{exact:true})).toBeVisible()
 await checkout.getByRole('button',{name:'Confirmar',exact:true}).click()
 await expect(checkout).toBeHidden()
 expect((await data(page,`customer_packages?id=eq.${pkg.id}`))[0].used_sessions).toBe(1)
 expect((await data(page,`package_usages?booking_id=eq.${b.id}`))).toHaveLength(1)
 const ledger=await data(page,`financial_transactions?shop_id=eq.${shop.id}`)
 expect(ledger.reduce((sum:number,t:{amount:string})=>sum+Number(t.amount),0)).toBe(200)
 console.log('Stage: /painel/dashboard?aba=packages')
 await page.goto('/painel/dashboard?aba=packages')
 await page.getByRole('button',{name:'Editar',exact:true}).first().click()
 await page.getByLabel('Total de sessões').fill('6')
 await page.getByRole('button',{name:'Salvar alterações',exact:true}).click()
 expect((await data(page,`customer_packages?id=eq.${pkg.id}`))[0].total_sessions).toBe(6)
 console.log('Stage: /painel/dashboard?aba=reports')
 await page.goto('/painel/dashboard?aba=reports')
 await expect(page.getByText('R$ 200,00',{exact:true})).toBeVisible()
})
