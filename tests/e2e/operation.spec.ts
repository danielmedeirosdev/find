import {data} from './api'
import {test,expect} from '@playwright/test'
import fs from 'node:fs'
const account=JSON.parse(fs.readFileSync(process.env.ONEFIND_QA_ACCOUNT||'/tmp/onefind-qa-account.json','utf8'))
const fixture=JSON.parse(fs.readFileSync('/tmp/onefind-qa-fixture.json','utf8'))
test('real operational flow persists after editing, payment and relogin',async({page})=>{
 await page.setViewportSize({width:375,height:812})
 await page.goto('/painel')
 await page.getByPlaceholder('Ex: contato@negocio.com').fill(account.email)
 await page.getByPlaceholder('Sua senha').fill(account.password)
 await page.getByRole('button',{name:'Entrar',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Seu dia no onefind'})).toBeVisible({timeout:30000})
 const professionals=await data(page,'barbers','POST',{shop_id:fixture.shopId,name:'UI QA '+Date.now()})
 const tomorrow=new Date();tomorrow.setDate(tomorrow.getDate()+1)
 await data(page,'barber_schedule','POST',{barber_id:professionals[0].id,day_of_week:tomorrow.getDay(),is_active:true,start_time:'09:00',end_time:'18:00'})
 const bookingId=await data(page,'rpc/create_operational_booking','POST',{p_shop_id:fixture.shopId,p_barber_id:professionals[0].id,p_customer_id:fixture.customerId,p_pet_id:fixture.petId,p_date:tomorrow.toISOString().slice(0,10),p_time:'10:00',p_service_ids:fixture.serviceIds.slice(0,2)})
 const check=async()=>(await data(page,`bookings?id=eq.${bookingId}&select=*,booking_services(*)`))[0]
 await page.goto('/painel/dashboard?aba=agenda')
 await page.getByRole('button',{name:'Próximos',exact:true}).click()
 const card=page.getByTestId(`booking-${bookingId}`)
 await expect(card).toBeVisible()
 await card.getByRole('button',{name:'Confirmar',exact:true}).click()
 await expect.poll(async()=>(await check()).status,{timeout:20000}).toBe('confirmed')
 await card.getByRole('button',{name:'Iniciar',exact:true}).click()
 await expect.poll(async()=>(await check()).status,{timeout:20000}).toBe('in_progress')
 await card.getByRole('button',{name:'Editar / adicionar serviços'}).click()
 const dialog=page.getByRole('dialog',{name:'Editar atendimento'})
 for(const width of [320,375,390,430]){await page.setViewportSize({width,height:568});const box=await dialog.locator(':scope > div').boundingBox();expect(box!.height).toBeLessThanOrEqual(568);expect(box!.width).toBeLessThanOrEqual(width)}
 await page.setViewportSize({width:375,height:812})
 await dialog.locator(`input[value="${fixture.serviceIds[2]}"]`).check()
 await dialog.getByLabel('Observações').fill('QA atualizado durante atendimento')
 await dialog.getByRole('button',{name:'Salvar atendimento'}).click()
 await expect(dialog).toBeHidden()
 await expect.poll(async()=>(await check()).booking_services.length).toBe(3)
 expect(Number((await check()).quoted_amount)).toBe(90)
 await card.getByRole('button',{name:'Finalizar atendimento'}).click()
 const checkout=page.getByRole('dialog',{name:'Finalizar atendimento'})
 await expect(checkout.getByText('R$ 90,00',{exact:true})).toBeVisible()
 await checkout.getByRole('button',{name:'Confirmar',exact:true}).click()
 await expect(checkout).toBeHidden()
 await expect.poll(async()=>(await check()).status).toBe('completed')
 const ledger=await data(page,`financial_transactions?booking_id=eq.${bookingId}`)
 expect(ledger).toHaveLength(1);expect(Number(ledger[0].amount)).toBe(90)
 await page.goto('/painel/dashboard?aba=cashflow')
 await expect(page.getByRole('heading',{name:'Fluxo de Caixa'})).toBeVisible()
 await page.getByRole('button',{name:/Conta de/}).click()
 await page.getByRole('button',{name:'Sair da conta'}).click()
 await expect(page.getByRole('heading',{name:'Entrar no painel'})).toBeVisible()
 await page.getByPlaceholder('Ex: contato@negocio.com').fill(account.email)
 await page.getByPlaceholder('Sua senha').fill(account.password)
 await page.getByRole('button',{name:'Entrar',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Seu dia no onefind'})).toBeVisible()
 expect((await check()).status).toBe('completed')
 await page.screenshot({path:'/tmp/onefind-operation-complete.png',fullPage:true})
})
