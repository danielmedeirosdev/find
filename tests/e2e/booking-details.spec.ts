import { test, expect } from '@playwright/test'
import fs from 'node:fs'
import { data } from './api'
const account = JSON.parse(fs.readFileSync(process.env.ONEFIND_QA_ACCOUNT || '/tmp/onefind-qa-account.json', 'utf8'))
const fixture = JSON.parse(fs.readFileSync('/tmp/onefind-qa-fixture.json', 'utf8'))
test('phone-only registration, inline pet, notes and taxi persist through receipt, payment and profile completion', async ({ page }) => {
  test.setTimeout(300000)
  await page.setViewportSize({ width: 375, height: 812 })
  const login = async () => {
    await page.goto('/painel')
    await page.getByPlaceholder('Ex: contato@negocio.com').fill(account.email)
    await page.getByPlaceholder('Sua senha').fill(account.password)
    await page.getByRole('button', { name: 'Entrar', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Seu dia no onefind' })).toBeVisible({ timeout: 30000 })
  }
  await login()
  const suffix = String(Date.now()), phone = '199' + suffix.slice(-8)
  const staff = (await data(page, 'barbers', 'POST', { shop_id: fixture.shopId, name: `QA Detalhes ${suffix}` }))[0]
  const service = (await data(page, 'services', 'POST', { shop_id: fixture.shopId, name: `QA Banho Detalhes ${suffix}`, price: 42.5, duration_minutes: 30 }))[0]
  await data(page, 'service_barbers', 'POST', { shop_id: fixture.shopId, service_id: service.id, barber_id: staff.id })
  await data(page, 'service_pet_transport', 'POST', { shop_id: fixture.shopId, service_id: service.id, enabled: true, pricing_mode: 'fixed', fee: 12.5 })
  const tomorrow = new Date(); tomorrow.setDate(tomorrow.getDate() + 1)
  const date = tomorrow.toISOString().slice(0, 10)
  await data(page, 'barber_schedule', 'POST', { barber_id: staff.id, day_of_week: tomorrow.getDay(), is_active: true, start_time: '09:00', end_time: '18:00' })
  const note = 'QA: alergia a perfume', address = 'Rua Fictícia dos Testes, 123', instructions = 'Portão azul. Ligar ao chegar.'
  await page.goto('/painel/dashboard?aba=agenda')
  await page.getByRole('button', { name: '+ Novo agendamento', exact: true }).click()
  await page.getByRole('button', { name: '+ Buscar ou cadastrar por WhatsApp', exact: true }).click()
  await page.getByLabel('WhatsApp do cliente', { exact: true }).fill('12')
  await page.getByRole('button', { name: 'Usar este WhatsApp', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('WhatsApp válido')
  await page.getByLabel('WhatsApp do cliente', { exact: true }).fill(phone)
  await page.getByRole('button', { name: 'Usar este WhatsApp', exact: true }).click()
  await expect(page.getByText('Contato salvo pelo WhatsApp.', { exact: false })).toBeVisible()
  const customer = (await data(page, `shop_customers?shop_id=eq.${fixture.shopId}&phone=eq.${phone}`))[0]
  expect(customer.name).toBe('')
  await page.getByRole('button', { name: '+ Buscar ou cadastrar por WhatsApp', exact: true }).click()
  await page.getByLabel('WhatsApp do cliente', { exact: true }).fill('+55' + phone)
  await page.getByRole('button', { name: 'Usar este WhatsApp', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Cliente', exact: true })).toHaveValue(customer.id)
  expect(await data(page, `shop_customers?shop_id=eq.${fixture.shopId}&phone=eq.${phone}`)).toHaveLength(1)
  await page.getByRole('button', { name: '+ Cadastrar pet aqui', exact: true }).click()
  await page.getByLabel('Nome do pet', { exact: true }).fill(`QA Pet Detalhes ${suffix}`)
  await page.getByRole('button', { name: 'Salvar pet e selecionar', exact: true }).click()
  await expect(page.getByText('Pet cadastrado e selecionado.', { exact: true })).toBeVisible()
  const pet = (await data(page, `pets?customer_id=eq.${customer.id}`))[0]
  await expect(page.getByRole('combobox', { name: 'Pet', exact: true })).toHaveValue(pet.id)
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  await page.getByRole('checkbox', { name: new RegExp(service.name) }).check()
  await page.getByLabel('Observação do atendimento (opcional)', { exact: true }).fill(note)
  await page.getByRole('button', { name: 'Buscar em casa', exact: true }).click()
  await page.getByLabel('Endereço da busca', { exact: true }).fill(address)
  await page.getByLabel('Instruções para a equipe (opcional)', { exact: true }).fill(instructions)
  await page.getByLabel('Valor do Táxi Pet (opcional)', { exact: true }).fill('-1')
  await expect(page.getByRole('alert')).toContainText('valor válido')
  await page.getByLabel('Valor do Táxi Pet (opcional)', { exact: true }).fill('')
  for (const width of [320, 375, 390, 430]) {
    await page.setViewportSize({ width, height: 812 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.screenshot({ path: '/tmp/onefind-booking-details.png', fullPage: true })
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  const picker = page.getByTestId('booking-schedule-picker')
  await picker.getByRole('group', { name: 'Dia da semana', exact: true }).getByRole('button').click()
  await picker.locator(`[data-date="${date}"]`).click()
  await picker.getByRole('button', { name: '10:00', exact: true }).click()
  await expect(page.getByText('Total: R$ 55,00', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Confirmar agendamento', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Concluir', exact: true })).toBeVisible({ timeout: 30000 })
  await expect(page.getByText(note, { exact: true })).toBeVisible()
  await expect(page.getByText(address, { exact: true })).toBeVisible()
  await expect(page.getByText(instructions, { exact: true })).toBeVisible()
  await expect(page.getByText('R$ 55,00', { exact: true })).toBeVisible()
  const link = await page.getByRole('link', { name: /Mandar comprovante/ }).getAttribute('href')
  const message = new URL(link!).searchParams.get('text')!
  expect(message).toContain(note); expect(message).toContain(address); expect(message).toContain(instructions); expect(message).toContain('55,00')
  const booking = (await data(page, `bookings?shop_customer_id=eq.${customer.id}&select=*`))[0]
  expect(booking.notes).toBe(note); expect(booking.pet_transport_address).toBe(address); expect(booking.pet_transport_notes).toBe(instructions)
  expect(Number(booking.pet_transport_fee)).toBe(12.5); expect(Number(booking.quoted_amount)).toBe(55)
  await page.getByRole('button', { name: 'Concluir', exact: true }).click()
  await page.getByRole('button', { name: 'Próximos', exact: true }).click()
  const card = page.getByTestId(`booking-${booking.id}`)
  await expect(card).toContainText(note); await expect(card).toContainText(address)
  await card.getByRole('button', { name: 'Confirmar', exact: true }).click()
  await page.getByRole('button', { name: 'Salvar e confirmar', exact: true }).click()
  await expect(card.getByRole('button', { name: 'Iniciar', exact: true })).toBeVisible()
  await card.getByRole('button', { name: 'Iniciar', exact: true }).click()
  await card.getByRole('button', { name: 'Finalizar atendimento', exact: true }).click()
  const checkout = page.getByRole('dialog', { name: 'Finalizar atendimento', exact: true })
  await expect(checkout.getByText('R$ 55,00', { exact: true })).toBeVisible()
  await checkout.getByRole('button', { name: 'Confirmar', exact: true }).click()
  await expect(checkout).toBeHidden()
  const ledger = await data(page, `financial_transactions?booking_id=eq.${booking.id}`)
  expect(ledger).toHaveLength(1); expect(Number(ledger[0].amount)).toBe(55)
  await page.goto('/painel/dashboard?aba=cashflow')
  await expect(page.getByText(ledger[0].description, { exact: true }).locator('..').locator('..')).toContainText('55,00')
  await page.goto('/painel/dashboard?aba=customers')
  await page.getByLabel('Buscar cliente', { exact: true }).fill(phone)
  await page.locator('button').filter({ hasText: 'Complete os dados quando quiser' }).click()
  await page.getByLabel('Nome (opcional)', { exact: true }).fill('QA Cliente completado depois')
  await page.getByRole('button', { name: 'Salvar cliente', exact: true }).click()
  await expect.poll(async () => (await data(page, `shop_customers?id=eq.${customer.id}`))[0].name).toBe('QA Cliente completado depois')
  // An unnamed contact is also able to complete its name through the public flow.
  const publicPhone = String(Number(phone) + 1)
  const publicCustomer = await data(page, 'rpc/quick_register_customer', 'POST', { p_shop_id: fixture.shopId, p_phone: publicPhone })
  const publicPet = (await data(page, 'pets', 'POST', { shop_id: fixture.shopId, customer_id: publicCustomer.id, name: `QA Pet Público ${suffix}`, size: 'medio' }))[0]
  await page.evaluate(() => localStorage.clear())
  await page.goto(`/pet/${fixture.shopId}`)
  await page.getByPlaceholder('Ex: (11) 99999-9999').fill(publicPhone)
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  await page.getByPlaceholder('Ex: Maria Silva').fill('QA Tutor pelo site')
  await page.getByRole('button', { name: new RegExp(publicPet.name) }).click()
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  await page.getByRole('checkbox', { name: new RegExp(service.name) }).check()
  await page.getByRole('button', { name: 'Buscar em casa', exact: true }).click()
  await page.getByLabel('Endereço da busca', { exact: true }).fill(address)
  await page.getByLabel('Instruções para a equipe (opcional)', { exact: true }).fill('QA retirada pública')
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  await picker.getByRole('group', { name: 'Dia da semana', exact: true }).getByRole('button').click()
  await picker.locator(`[data-date="${date}"]`).click()
  await picker.getByRole('button', { name: '14:00', exact: true }).click()
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar agendamento', exact: true }).click()
  await expect(page).toHaveURL(/confirmacao\//, { timeout: 30000 })
  await page.evaluate(() => localStorage.clear())
  await login()
  const publicSaved = (await data(page, `bookings?shop_customer_id=eq.${publicCustomer.id}`))[0]
  expect(Number(publicSaved.quoted_amount)).toBe(55); expect(publicSaved.pet_transport_notes).toBe('QA retirada pública')
  expect((await data(page, `shop_customers?id=eq.${publicCustomer.id}`))[0].name).toBe('QA Tutor pelo site')
})
